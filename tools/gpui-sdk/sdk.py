#!/usr/bin/env python3
"""Explicit Linux SDK build/install and Cargo selection; never a compiler wrapper."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
MARKER = "# Generated by tools/gpui-sdk/sdk.py; machine-local SDK selection.\n"


def digest(path):
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def output(command):
    return subprocess.check_output(command, text=True).strip()


def safe_selection(directory):
    # Inspect rustup state before invoking a proxy that could install a pin.
    if any(os.environ.get(name) for name in ["RUSTUP_TOOLCHAIN", "RUSTC", "CARGO", "RUSTC_WRAPPER", "RUSTC_WORKSPACE_WRAPPER", "RUSTFLAGS", "CARGO_ENCODED_RUSTFLAGS", "RUSTDOCFLAGS", "CARGO_BUILD_TARGET"]):
        raise ValueError("Resolve custom Rust selection/overrides explicitly before using the SDK tool")
    rustc = shutil.which("rustc")
    cargo = shutil.which("cargo")
    if not rustc or not cargo:
        raise ValueError("Rust and Cargo must already be installed on PATH")
    rustup = shutil.which("rustup")
    proxy = Path(rustc).resolve().name == "rustup" or (rustup and os.path.samefile(rustc, rustup))
    if not proxy:
        return
    if not os.path.samefile(cargo, rustc):
        raise ValueError("Cargo and rustc select different installations")
    home = Path(os.environ.get("RUSTUP_HOME", Path.home() / ".rustup"))
    settings = tomllib.loads((home / "settings.toml").read_text())
    expected = tomllib.loads((ROOT / "rust-toolchain.toml").read_text())["toolchain"]
    selected = settings.get("default_toolchain", "")
    if selected != expected["channel"] + "-x86_64-unknown-linux-gnu":
        raise ValueError("Default Rust differs from the repository pin; resolve it without automatic installation")
    parents = [directory.resolve(), *directory.resolve().parents]
    if any(Path(key).resolve() in parents for key in settings.get("overrides", {})):
        raise ValueError("A directory toolchain override is active; resolve it explicitly")
    for parent in parents:
        pin = parent / "rust-toolchain.toml"
        legacy = parent / "rust-toolchain"
        if legacy.exists():
            raise ValueError("Legacy toolchain override requires explicit selection review")
        if pin.exists():
            requirement = tomllib.loads(pin.read_text())["toolchain"]
            if requirement != expected:
                raise ValueError("Active Rust pin differs from the approved SDK compiler/components")
            break
    toolchain = home / "toolchains" / selected
    for name in ["rustc", "cargo", "rustfmt", "cargo-clippy"]:
        if not (toolchain / "bin" / name).is_file():
            raise ValueError(f"Required installed Rust executable is missing: {name}")
    components = (toolchain / "lib/rustlib/components").read_text().splitlines()
    for component in ["rustc", "cargo", "rust-std", *expected.get("components", [])]:
        if not any(line.startswith(component + "-") for line in components):
            raise ValueError(f"Required Rust component {component} is not installed; do not install automatically")


def compiler():
    safe_selection(Path.cwd())
    version = output(["rustc", "-vV"]) + "\n"
    host = next(line.removeprefix("host: ") for line in version.splitlines() if line.startswith("host: "))
    if host != "x86_64-unknown-linux-gnu":
        raise ValueError("The development SDK currently supports x86_64 Linux only; use source-toolkit elsewhere")
    return version, host


def common_cache():
    config = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo")) / "config.toml"
    build = tomllib.loads(config.read_text()).get("build", {}).get("build-dir")
    if not build or not Path(build).is_absolute() or not Path(build).is_dir():
        raise ValueError("Configure the owner-approved shared Cargo build.build-dir before building the SDK")


def copy_artifact(source, directory, records):
    destination = directory / source.name
    checksum = digest(source)
    if destination.exists():
        if digest(destination) != checksum:
            raise ValueError(f"Conflicting SDK artifact name: {source.name}")
        return
    shutil.copy2(source, destination)
    records[source.name] = checksum


def collect_artifacts(messages):
    artifacts = set()
    for message in messages:
        if message.get("reason") == "compiler-artifact":
            artifacts.update(Path(name) for name in message["filenames"]
                             if Path(name).suffix in {".rlib", ".rmeta", ".so", ".a"})
        if message.get("reason") == "build-script-executed":
            out_dir = Path(message["out_dir"]).resolve()
            names = [name.split("=", 1)[-1].split(":", 1)[0]
                     for name in message.get("linked_libs", [])]
            for search in message.get("linked_paths", []):
                directory = Path(search.split("=", 1)[-1]).resolve()
                # System libraries are OS dependencies, not SDK payload.
                if directory.is_dir() and directory.is_relative_to(out_dir):
                    for name in names:
                        artifacts.update(p for p in directory.iterdir() if p.is_file()
                                         and (p.name == f"lib{name}.a" or p.name == f"lib{name}.so"
                                              or p.name.startswith(f"lib{name}.so.")))
    return artifacts


def approved_graph():
    def external(lock):
        packages = tomllib.loads(lock.read_text())["package"]
        return {(p["name"], p["version"], p.get("source"), p.get("checksum"))
                for p in packages if p.get("source")}
    if not external(HERE / "Cargo.lock") <= external(ROOT / "Cargo.lock"):
        raise ValueError("SDK lock differs from the approved workspace dependency graph")


def build_install(prefix):
    approved_graph()
    common_cache()
    version, host = compiler()
    log = HERE / "target" / "sdk-build.jsonl"
    log.parent.mkdir(exist_ok=True)
    command = ["cargo", "rustc", "--manifest-path", str(HERE / "Cargo.toml"),
               "--lib", "--locked", "--offline", "--message-format=json", "--", "-Cprefer-dynamic"]
    safe_selection(Path.home())
    producer_version = subprocess.check_output(["rustc", "-vV"], cwd=Path.home(), text=True)
    if producer_version != version:
        raise ValueError("Home and project select different Rust compilers; resolve selection explicitly")
    with log.open("w") as stream:
        subprocess.run(command, cwd=Path.home(), stdout=stream, check=True)
    messages = [json.loads(line) for line in log.read_text().splitlines() if line.startswith("{")]
    artifacts = collect_artifacts(messages)
    runtime_dir = Path(output(["rustc", "--print", "target-libdir"]))
    runtimes = list(runtime_dir.glob("libstd-*.so"))
    if len(runtimes) != 1:
        raise ValueError("Expected one matching installed Rust standard-library runtime")
    artifacts.update(runtimes)
    library = HERE / "target/debug/libgpui_kit_sdk.so"
    if library not in artifacts:
        raise ValueError("Cargo did not report the expected SDK dylib")
    prefix = prefix.expanduser().resolve()
    prefix.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".install-", dir=prefix))
    try:
        libs = staging / "lib"
        libs.mkdir()
        records = {}
        for artifact in sorted(artifacts):
            copy_artifact(artifact, libs, records)
        identity = dict(format=1, compiler=version, target=host, kit="0.9.1",
                        lock_sha256=digest(HERE / "Cargo.lock"), artifacts=records)
        build_id = hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()
        identity["build_id"] = build_id
        (staging / "manifest.json").write_text(json.dumps(identity, indent=2, sort_keys=True) + "\n")
        for name, value in [("rustc-version.txt", version), ("target.txt", host + "\n"),
                            ("kit-version.txt", "0.9.1\n")]:
            (staging / name).write_text(value)
        destination = prefix / build_id
        if destination.exists():
            verify(destination)
            if json.loads((destination / "manifest.json").read_text()) != identity:
                raise ValueError("Existing SDK identity does not match; refusing replacement")
        else:
            staging.rename(destination)
        print(destination)
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def verify(directory):
    approved_graph()
    directory = directory.expanduser().resolve(strict=True)
    manifest = json.loads((directory / "manifest.json").read_text())
    version, host = compiler()
    if manifest.get("format") != 1 or manifest["compiler"] != version or manifest["target"] != host:
        raise ValueError("Installed SDK does not match the selected Rust compiler/target")
    identity = dict(manifest)
    build_id = identity.pop("build_id")
    computed = hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()
    if computed != build_id or directory.name != build_id:
        raise ValueError("Installed SDK build identity/directory mismatch")
    if manifest["lock_sha256"] != digest(HERE / "Cargo.lock"):
        raise ValueError("Installed SDK uses another locked backend graph; build/select the approved graph")
    if manifest["kit"] != "0.9.1":
        raise ValueError("Installed SDK does not match the approved GPUI Kit version")
    for name, checksum in manifest["artifacts"].items():
        if Path(name).name != name or digest(directory / "lib" / name) != checksum:
            raise ValueError(f"Missing or changed SDK artifact: {name}")
    return directory, manifest


def select(directory):
    directory, manifest = verify(directory)
    config = ROOT / ".cargo/config.toml"
    if config.exists() and not config.read_text().startswith(MARKER):
        raise ValueError(f"Refusing to overwrite existing Cargo configuration: {config}")
    libs = directory / "lib"
    images = [name for name in manifest["artifacts"] if name.startswith("libimage-") and name.endswith(".rlib")]
    if len(images) != 1:
        raise ValueError("Expected exactly one SDK image artifact")
    flags = [f"--extern=gpui_kit={libs / 'libgpui_kit_sdk.so'}", f"--extern=image={libs / images[0]}",
             f"-Ldependency={libs}", "-C", f"link-arg=-Wl,-rpath,{libs}"]
    text = MARKER + "[build]\ntarget=" + json.dumps(manifest["target"]) + "\nrustdocflags=" + json.dumps(flags)
    text += "\n[target." + manifest["target"] + "]\nrustflags=" + json.dumps(flags)
    text += "\n[env]\nGPUI_KIT_SDK=" + json.dumps(str(directory)) + "\n"
    config.parent.mkdir(exist_ok=True)
    config.write_text(text)
    print(f"Selected {directory}\nOrdinary cargo build/test/clippy now consume this SDK; they never rebuild it.")


def source_mode():
    config = ROOT / ".cargo/config.toml"
    if config.exists():
        if not config.read_text().startswith(MARKER):
            raise ValueError("Refusing to remove Cargo configuration not generated by this tool")
        config.unlink()
    print("SDK configuration removed. Use --features source-toolkit for source builds;")
    print("add toolkit-test-support for workspace tests and all-target Clippy.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    build = commands.add_parser("build-install")
    build.add_argument("--prefix", type=Path, default=Path.home() / ".local/lib/gpui-kit-sdk")
    for name in ["select", "verify"]:
        commands.add_parser(name).add_argument("directory", type=Path)
    commands.add_parser("source-mode")
    args = parser.parse_args()
    try:
        if args.command == "build-install":
            build_install(args.prefix)
        elif args.command == "select":
            select(args.directory)
        elif args.command == "verify":
            directory, _ = verify(args.directory)
            print(f"Verified {directory}")
        else:
            source_mode()
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"SDK error: {error}\n")


if __name__ == "__main__":
    main()
